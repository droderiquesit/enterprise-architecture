def test_postrender_fails_closed(rendered, tmp_path):
    manifest = "---\n# Source: datadog/templates/daemonset.yaml\nkind: DaemonSet\nspec:\n  template:\n    spec:\n      initContainers:\n      - name: x\n"
    ok = _run(["sh", str(POSTRENDER), "--image", FETCH_IMAGE, "--expect", "1"], input=manifest)
    assert ok.returncode == 0 and "dsv-fetch-install" in ok.stdout
    wrong_count = _run(["sh", str(POSTRENDER), "--image", FETCH_IMAGE, "--expect", "3"], input=manifest)
    assert wrong_count.returncode != 0 and "expected 3" in wrong_count.stderr
    tag_only = _run(["sh", str(POSTRENDER), "--image", "ehacr.azurecr.io/dsv-fetch:2.0.0", "--expect", "1"], input=manifest)
    assert tag_only.returncode == 2


