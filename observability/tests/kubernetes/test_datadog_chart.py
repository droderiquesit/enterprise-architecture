def _workloads(docs: list[dict]) -> dict[str, dict]:
    return {d["metadata"]["name"]: d for d in docs if d["kind"] in ("DaemonSet", "Deployment") and d["metadata"]["name"].startswith("datadog")}


def _env(c: dict) -> list[dict]:
    return c.get("env", [])


def test_layers_order_and_no_secret(rendered):
    layers = rendered["layers"]
    assert layers[0] == (MODULE / "values" / "base.yaml").read_text(), "layer 0 = values/base.yaml verbatim"
    fleet = yaml.safe_load(layers[1])
    assert fleet["datadog"]["apiKey"] == f"ENC[{API_REF}]" and "apiKeyExistingSecret" not in fleet["datadog"]
    assert rendered["args"][1:] == ["--image", FETCH_IMAGE, "--expect", "3"]


def test_every_datadog_workload_gets_the_dsv_fetch_install_init_container(rendered):
    wl = _workloads(rendered["docs"])
    assert set(wl) == {"datadog", "datadog-cluster-agent", "datadog-clusterchecks"}
    for name, d in wl.items():
        spec = d["spec"]["template"]["spec"]
        init = spec["initContainers"][0]
        assert init["name"] == "dsv-fetch-install" and init["image"] == FETCH_IMAGE, name
        assert init["command"] == ["/opt/dsv-fetch/dsv-fetch", "install", "--dest", "/dsv-fetch-out/dsv-fetch"], name
        sc = init["securityContext"]
        assert sc["runAsUser"] == 0 and sc["readOnlyRootFilesystem"] and not sc["allowPrivilegeEscalation"] and sc["capabilities"]["drop"] == ["ALL"], name
        vol = {v["name"]: v for v in spec["volumes"]}["dsv-fetch"]
        assert vol["emptyDir"]["medium"] == "Memory", name
        assert init["volumeMounts"] == [{"name": "dsv-fetch", "mountPath": "/dsv-fetch-out"}], name


