def _check_secret_backend(rendered):
    wl = _workloads(rendered["docs"])
    checked = []
    for name, d in wl.items():
        for c in d["spec"]["template"]["spec"]["containers"]:
            env = _env(c)
            names = [e["name"] for e in env]
            if "DD_API_KEY" not in names:
                continue
            checked.append(f"{name}/{c['name']}")
            dupes = sorted({n for n in names if names.count(n) > 1})
            assert not dupes, f"{name}/{c['name']}: duplicate env {dupes}"
            ev = {e["name"]: e for e in env}
            assert ev["DD_SECRET_BACKEND_COMMAND"]["value"] == "/opt/dsv-fetch/dsv-fetch", f"{name}/{c['name']}"
            assert ev["DD_SECRET_BACKEND_ARGUMENTS"]["value"] == "agent-backend"
            # chart-generated DD_API_KEY / DD_SECRET_BACKEND_* + our DSV_* entries: each exactly once (no duplicate
            # that a later entry would win), DD_API_KEY from the chart Secret (= the ENC[] reference)
            assert ev["DD_API_KEY"]["valueFrom"]["secretKeyRef"]["name"] == "datadog"
            assert ev["DSV_BASE_URL"]["value"] == "https://contoso.secretsvaultcloud.com/v1" and ev["DSV_AUTH"]["value"] == "azure", f"{name}/{c['name']}"
            mounts = {m["name"]: m for m in c.get("volumeMounts", [])}
            assert mounts["dsv-fetch"]["mountPath"] == "/opt/dsv-fetch" and mounts["dsv-fetch"]["readOnly"], f"{name}/{c['name']}"
    for must in ("datadog/agent", "datadog/trace-agent", "datadog-cluster-agent/cluster-agent", "datadog-clusterchecks/agent"):
        assert must in checked, (must, checked)
    blob = json.dumps(rendered["docs"])
    assert '"name": "DD_SECRET_BACKEND_COMMAND", "value": ""' not in blob, "no secret-backend opt-out for the Cluster Agent"


