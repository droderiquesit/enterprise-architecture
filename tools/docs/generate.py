from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
GENERATED = "<!-- GENERATED by tools/docs/generate.py - do not edit by hand; run `python3 tools/docs/generate.py` -->"
ENV = "dev"


def load(rel: str):
    return yaml.safe_load((REPO / rel).read_text())


def esc(text) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def code_list(items) -> str:
    return ", ".join(f"`{i}`" for i in items) if items else "-"


# --------------------------------------------------------------------------------------------- components
def profiles_by_component() -> dict[str, list[str]]:
    out: dict[str, list[str]] = defaultdict(list)
    for f in sorted((REPO / "environments/profiles").glob("*.yaml")):
        p = yaml.safe_load(f.read_text())
        for cid in p.get("components") or []:
            out[cid].append(p["profile"])
    return out


def root_files_present(comp: dict) -> str:
    path = REPO / comp["path"]
    if not path.exists():
        return "no"
    if comp["kind"] == "terraform":
        tf = {p.name for p in path.glob("*.tf")}
        logic = tf - {"backend.tf", "providers.tf", "versions.tf", "variables.tf", "variables-environment.tf", "outputs.tf"}
        tests = any(path.glob("tests/*.tftest.hcl"))
        if not logic:
            return "partial (no resource files yet)"
        return "yes" + ("" if tests else " (no tests/)")
    return "yes"


