#!/usr/bin/env python3
"""Generate the catalog-derived documentation pages (deterministic, no timestamps).

    python3 tools/docs/generate.py            # write every generated page
    python3 tools/docs/generate.py --check    # exit 1 when a committed page is stale

Outputs
  docs/guides/component-ownership.md          from catalog/components.yaml + environments/profiles/*.yaml
  docs/guides/architecture-deployment-matrix.md
                                              from catalog/architecture-matrix.yaml + catalog/telemetry-capabilities.yaml
                                              + tools/docs/architecture-matrix-supplement.yaml (columns the catalog
                                              leaves empty, each value citing the README it was taken from)
  docs/runbooks/alerts/<service>.md           one page per rendered service in
                                              observability/onboarding/rendered/<env>/*.json: the monitors of that
                                              service grouped by runbook section (anchors match `#<section>`)
  README.md (block between the STATUS markers) catalog/component counts

Dependencies: Python 3.11+, PyYAML.
"""

from __future__ import annotations

import argparse
import glob
import json
