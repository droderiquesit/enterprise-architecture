SECTION_INDEX = "../alert-response.md"


def render_alert_runbooks() -> dict[str, str]:
    pages: dict[str, str] = {}
    rendered = sorted(glob.glob(str(REPO / f"observability/onboarding/rendered/{ENV}/*.json")))
    index = [GENERATED, "", "# Alert runbooks per service", "",
             f"One page per service rendered from `observability/onboarding/rendered/{ENV}/*.json`. Each monitor message links to",
             "`<runbook_url>#<section>`; the anchors on these pages match those sections, and each section points to the shared",
             f"procedure in [alert-response.md]({SECTION_INDEX}).",
             "",
             "> The lab manifests (`observability/onboarding/<env>/*.yaml`) currently set `runbook_url` to",
             "> `https://runbooks.example.com/enterprise-hello/<service>` (a placeholder host). To make monitor links resolve to",
             "> these pages, the observability owner must point `metadata.runbook_url` at the published location of this",
             "> directory (see [known limitations](../../known-limitations.md#documentation-and-links)).",
             "",
             "| Service | Team | Runbook sections |", "|---|---|---|"]
    for f in rendered:
        d = json.loads(Path(f).read_text())
        svc = d.get("service") or Path(f).stem
        md = d.get("metadata") or {}
        monitors = d.get("monitors") or []
        if isinstance(monitors, dict):
            monitors = [dict(v, key=k) for k, v in monitors.items()]
        slos = d.get("slos") or []
        sections: dict[str, list[dict]] = defaultdict(list)
        for mon in monitors:
            url = mon.get("runbook_url") or ""
            sec = url.split("#", 1)[1] if "#" in url else mon.get("runbook_section", "")
            if sec:
                sections[sec].append(mon)
        raw = Path(f).read_text()
        base = md.get("runbook_url") or ""
        if base:
            for sec in set(re.findall(re.escape(base) + r"#([a-z0-9-]+)", raw)):
                sections.setdefault(sec, [])
        for slo in slos:
            for br in slo.get("burn_rate_alerts") or []:
                url = br.get("runbook_url") or ""
                if "#" in url:
                    sections[url.split("#", 1)[1]].append(dict(br, key=f"slo:{slo.get('name')}", type="slo alert"))
        team = md.get("team") or d.get("team") or "-"
        lines = [GENERATED, "", f"# Alert runbook: {svc}", "",
                 f"Service `{svc}` - team `{team}`, owner {md.get('owner') or d.get('owner') or '-'}, tier `{md.get('tier') or d.get('tier') or '-'}`,",
                 f"architecture `{(d.get('spec') or {}).get('architecture') or d.get('architecture') or '-'}`. Source: `observability/onboarding/{ENV}/{Path(f).stem}.yaml`",
                 f"(rendered `observability/onboarding/rendered/{ENV}/{Path(f).name}`).", "",
                 "Before acting on any no-data alert, check the telemetry pipeline canary ([telemetry-pipeline](telemetry-pipeline.md#pipeline-canary)):",
                 "a broken pipeline looks like silence.", ""]
        for sec in sorted(sections):
            lines += [f"## {sec}", "", f"Procedure: [alert-response.md#{sec}]({SECTION_INDEX}#{sec})", ""]
            mons = sections[sec]
            if mons:
                lines += ["| Monitor key | Name | Type | Severity |", "|---|---|---|---|"]
                for mon in sorted(mons, key=lambda x: str(x.get("key"))):
                    lines.append(f"| `{esc(mon.get('key'))}` | {esc(mon.get('name'))} | {esc(mon.get('type'))} | {esc(mon.get('severity') or mon.get('priority') or '-')} |")
                lines.append("")
            elif sec.startswith("slo"):
                lines += [f"SLO burn-rate alerts ({len(slos)} SLO(s) declared for this service).", ""]
        pages[f"docs/runbooks/alerts/{svc}.md"] = "\n".join(lines)
        index.append(f"| [{svc}]({svc}.md) | `{team}` | {', '.join(f'[{s}]({svc}.md#{s})' for s in sorted(sections))} |")
    index.append("")
    pages["docs/runbooks/alerts/README.md"] = "\n".join(index)
    return pages


